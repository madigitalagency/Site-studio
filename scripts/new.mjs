// Crée le squelette d'une nouvelle pièce (épisode ou film) et son dossier média.
// Usage :
//   npm run new -- --serie rouvray --saison 1 --episode 4 --slug 04-le-titre --titre "Le titre" --date 2026-11-01
//   npm run new -- --film mon-film --titre "Mon film" --format pub --univers marques --date 2026-11-12
// Options : --en "English title" --format <id de formats.json> --univers <id,id> --rendu photorealiste|roman-photo|...
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const a = Object.fromEntries(process.argv.slice(2).join(' ').split(/\s--/).filter(Boolean).map((s) => { const [k, ...v] = s.replace(/^--/, '').split(' '); return [k, v.join(' ').replace(/^"|"$/g, '')]; }));
const formats = JSON.parse(readFileSync('src/data/formats.json', 'utf8'));
const univers = JSON.parse(readFileSync('src/data/univers.json', 'utf8'));
if (!a.titre || !a.date) throw new Error('--titre et --date sont obligatoires');
let id, slug, serie;
if (a.serie) {
  if (!a.saison || !a.episode || !a.slug) throw new Error('--saison, --episode et --slug sont obligatoires pour un épisode');
  serie = JSON.parse(readFileSync(`src/content/series/${a.serie}.json`, 'utf8'));
  id = `${a.serie.replace(/-/g, '')}-s${a.saison}e${String(a.episode).padStart(2, '0')}`;
  slug = a.slug;
} else if (a.film) {
  id = a.film; slug = a.film;
} else throw new Error('--serie ou --film attendu');
const fichier = `src/content/pieces/${id}.json`;
if (existsSync(fichier)) throw new Error(`${fichier} existe déjà`);
const format = a.format ?? serie?.format_defaut ?? 'film-court';
if (!formats.some((f) => f.id === format)) throw new Error(`format inconnu : ${format} (${formats.map((f) => f.id).join(', ')})`);
const univ = (a.univers ?? serie?.univers ?? '').split(',').filter(Boolean);
for (const u of univ) if (!univers.some((x) => x.id === u)) throw new Error(`univers inconnu : ${u} (${univers.map((x) => x.id).join(', ')})`);
const piece = {
  slug,
  ...(serie ? { serie: a.serie, saison: Number(a.saison), episode: Number(a.episode) } : {}),
  titre: { fr: a.titre, ...(a.en ? { en: a.en } : {}) },
  pitch: serie?.episodes_titre_seul ? { fr: `${serie.titre.fr}, saison ${a.saison}, épisode ${Number(a.episode)}.`, en: `${serie.titre.en}, season ${a.saison}, episode ${Number(a.episode)}.` } : { fr: 'À ÉCRIRE', en: 'TO WRITE' },
  format, univers: univ, rendu: a.rendu ?? serie?.rendu ?? 'photorealiste',
  duree_s: { fr: 0 },
  orientations: ['9:16'],
  langues: ['fr'],
  date_publication: a.date,
  statut: 'brouillon',
  une: false, roger: false, annexe: false, fiche: true, vitrine: false,
  media: { poster: 'poster-916', v916: { fr: 'v916-fr' }, teaser: 'teaser.mp4' },
  sources_media: {},
  coulisses: { texte: { fr: '**L\'idée.** À ÉCRIRE\n\n**Ce qui était difficile.** À ÉCRIRE\n\n**Ce qu\'on a appris.** À ÉCRIRE', en: '' }, genere: { fr: ['images', 'animation des plans'], en: ['images', 'shot animation'] }, manuel: { fr: ['écriture', 'montage'], en: ['writing', 'editing'] }, images: [], chiffre: null },
  notions: [],
  carnet: null,
  sources: [],
  transcription: { fr: '' },
  liens: { instagram: null, tiktok: null },
  mention_ia: serie?.rendu === 'roman-photo' ? { fr: 'Images et musique générées par IA. Fiction.', en: 'Images and music generated by AI. Fiction.' } : { fr: 'Images, animation et voix générées par IA.', en: 'Images, animation and voice generated by AI.' },
};
writeFileSync(fichier, JSON.stringify(piece, null, 2) + '\n');
mkdirSync(`public/media/${id}`, { recursive: true });
console.log(`créé : ${fichier} (statut brouillon) et public/media/${id}/`);
console.log(`suite : npm run media -- ${id} <master.mp4>   puis compléter pitch, coulisses, sources, notions, durée ; RUNBOOK.md`);
